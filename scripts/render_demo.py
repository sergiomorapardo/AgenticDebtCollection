"""Render the README demo from a real offline Studio happy path; no keys, model or network."""

import argparse
import os
import re
import socket
import tempfile
import textwrap
from datetime import datetime
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TURNS = ["Hola", "Mi cédula es 1000000001", "1111", "quiero 3 cuotas desde 2026-10-20", "confirmo"]
WIDTH, LINE, WRAP, STEP = 960, 20, 74, 2.2
MONO = "ui-monospace,SFMono-Regular,Menlo,Consolas,monospace"


CREDENTIAL_PREFIXES = ("ANTHROPIC_", "LANGSMITH_", "LANGCHAIN_", "ELEVENLABS_")
PINNED_ENV = {
    "LANGSMITH_TRACING": "false",
    "COLLECTIONS_LLM_PROVIDER": "mock",
    "COLLECTIONS_RESPONSE_MODE": "streaming",
}


def no_network(*args, **kwargs):
    raise RuntimeError("The demo renderer must not use the network")


def offline_environment():
    for key in list(os.environ):
        if key.startswith(CREDENTIAL_PREFIXES):
            del os.environ[key]
    os.environ.update(PINNED_ENV)
    socket.socket.connect = socket.socket.connect_ex = socket.getaddrinfo = no_network


def run_happy_path():
    from langchain_core.messages import HumanMessage

    from agents.collections.agent import build_graph
    from agents.collections.memory import SQLiteRepository
    from agents.collections.runtime import AppContext

    graph = build_graph(studio=True)
    with tempfile.TemporaryDirectory() as directory:
        ctx = AppContext(
            SQLiteRepository(Path(directory) / "demo.sqlite3"),
            datetime.fromisoformat("2026-10-19T09:00:00-05:00"),
            provider="mock",
        )
        turns = []
        for index, text in enumerate(TURNS):
            nodes, reply = [], None
            for mode, chunk in graph.stream(
                {"messages": [HumanMessage(content=text, id=f"demo-{index}")]},
                config={"configurable": {"thread_id": "readme-demo"}},
                context=ctx,
                stream_mode=["updates", "values"],
            ):
                if mode == "updates":
                    nodes.extend(chunk)
                else:
                    reply = chunk.get("reply")
            # Elide the random agreement ID so regenerating the asset gives a stable diff.
            agent = re.sub(r"agreement-[0-9a-f]{16}", "agreement-…", reply["text"])
            turns.append({"user": text, "agent": agent, "stage": reply["stage"]})
            turns[-1]["nodes"] = nodes
        if len(ctx.repository.agreements()) != 1:
            raise RuntimeError("The happy path must record exactly one agreement")
    return turns


def render(turns):
    rows, y = [], 64
    for index, turn in enumerate(turns):
        lines = [("user", "Tú: " + turn["user"])]
        lines += [
            ("agent", line)
            for line in textwrap.wrap("Agente: " + turn["agent"], WRAP, subsequent_indent="  ")
        ]
        path = " → ".join(turn["nodes"]) + f"  [{turn['stage']}]"
        lines += [
            ("nodes", line)
            for line in textwrap.wrap(path, 112, initial_indent="  ↳ ", subsequent_indent="    ")
        ]
        text = "".join(
            f'<text x="24" y="{y + n * LINE}" class="{kind}">{escape(line)}</text>'
            for n, (kind, line) in enumerate(lines)
        )
        rows.append(f'<g class="turn t{index}">{text}</g>')
        y += len(lines) * LINE + 14
    height = y + 16
    cycle = round(STEP * (len(turns) + 2), 1)
    keyframes = "".join(
        f".t{i}{{animation:t{i} {cycle}s infinite}}"
        f"@keyframes t{i}{{0%,{100 * i * STEP / cycle:.1f}%{{opacity:0}}"
        f"{100 * (i * STEP + 0.4) / cycle:.1f}%,96%{{opacity:1}}100%{{opacity:0}}}}"
        for i in range(len(turns))
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height}" viewBox="0 0 {WIDTH} {height}" role="img" aria-labelledby="title">
<title id="title">Offline Studio happy path: identification, verification, a three-installment plan and one recorded commitment</title>
<style>
text{{font:14px {MONO};white-space:pre}}.nodes,.head{{font:12px {MONO}}}
.user{{fill:#7dd3fc;font-weight:600}}.agent{{fill:#e5e7eb}}.nodes{{fill:#86efac}}.head{{fill:#9ca3af}}
{keyframes}
@media (prefers-reduced-motion:reduce){{.turn{{animation:none!important;opacity:1}}}}
</style>
<rect width="100%" height="100%" rx="10" fill="#111827"/>
<circle cx="22" cy="20" r="6" fill="#f87171"/><circle cx="42" cy="20" r="6" fill="#fbbf24"/><circle cx="62" cy="20" r="6" fill="#34d399"/>
<text x="84" y="24" class="head">collections_agent · provider mock · synthetic fixture demo-001 · generated by scripts/render_demo.py</text>
{"".join(rows)}
</svg>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "docs/images/demo.svg")
    args = parser.parse_args()
    offline_environment()
    args.output.write_text(render(run_happy_path()), newline="\n")
    print(f"Wrote {args.output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
